"""
Prepare the documentation for Zensical.

Zensical builds the pages of a single folder, using a fixed configuration
file, and cannot run our Python code while building. The Duranta openairinterface5g documentation
is spread over the repository and needs adapting, so before each build:

1. every page and image is copied into build/docs-src/, keeping its path in
   the repository (so links between pages keep working), and the pages are
   adapted for the site (TOC markers, GitHub alerts, links to GitHub, label
   pills; see transforms.py and labels.py);
2. build/zensical.yml is written: the settings of zensical.toml plus the
   docs directory and the menu generated from doc/README.md.

The original documents are never changed.
"""

import filecmp
import os
import shutil

import yaml

try:
  import tomllib
except ModuleNotFoundError:  # Python 3.10: same module, installed with Zensical
  import tomli as tomllib

from . import labels, nav, repo, transforms

BUILD_DIR = os.path.join(repo.REPO_ROOT, "build")
# Staged documentation, and configuration used by Zensical (in BUILD_DIR, as
# Zensical requires the docs and site directories to be below the configuration).
DOCS_DIR = os.path.join(BUILD_DIR, "docs-src")
CONFIG_FILE = os.path.join(BUILD_DIR, "zensical.yml")
SITE_DIR = os.path.join(BUILD_DIR, "website")
BASE_CONFIG = os.path.join(repo.REPO_ROOT, "zensical.toml")

# Front matter of the overview page: it lists every page itself, so its (nearly
# empty) navigation sidebar is hidden.
NAV_SOURCE_FRONT_MATTER = "---\nhide:\n  - navigation\n---\n\n"


def base_config():
  """Settings of zensical.toml (its [project] table)."""
  with open(BASE_CONFIG, "rb") as f:
    return tomllib.load(f)["project"]


def prepare():
  """
  Stage the whole documentation and write the configuration.

  DOCS_DIR is updated in place rather than recreated: only changed files are
  written and only stale ones removed, so a build never disturbs a preview
  server running from the same DOCS_DIR (it would see missing pages).
  """
  state = sync({})
  _remove_stale(set(state))
  return state


def sync(state):
  """
  Bring the staged documentation up to date with the repository.

  state maps each published file to its modification time at the last sync
  (empty for a full staging). Only new or changed files are staged again,
  deleted ones are removed, and the configuration is rewritten when its
  content changes. Returns the new state.
  """
  config = base_config()
  url = config["repo_url"]
  labels.load_colors(url)
  files = repo.tracked_files()
  published = set(files)
  new_state = {f: os.path.getmtime(os.path.join(repo.REPO_ROOT, f)) for f in files}

  for path in set(state) - published:
    _remove(os.path.join(DOCS_DIR, path))
  for path in files:
    if state.get(path) != new_state[path]:
      _stage_file(path, published, url)

  # Paths in the generated configuration are relative to BUILD_DIR, where it is written.
  config["docs_dir"] = os.path.relpath(DOCS_DIR, BUILD_DIR)
  config["site_dir"] = os.path.relpath(SITE_DIR, BUILD_DIR)
  config["theme"]["custom_dir"] = os.path.relpath(os.path.join(repo.REPO_ROOT, config["theme"]["custom_dir"]), BUILD_DIR)
  config["nav"] = nav.build_nav()
  _write(CONFIG_FILE, "# Generated by doc/website/run.py, do not edit.\n" + yaml.safe_dump(config, sort_keys=False, allow_unicode=True))
  return new_state


def _stage_file(path, published, url):
  """Copy one page or image to DOCS_DIR; pages are adapted for the site."""
  src = os.path.join(repo.REPO_ROOT, path)
  dst = os.path.join(DOCS_DIR, path)
  if not path.lower().endswith(repo.PAGE_EXT):
    if not (os.path.exists(dst) and filecmp.cmp(src, dst, shallow=False)):
      os.makedirs(os.path.dirname(dst), exist_ok=True)
      shutil.copyfile(src, dst)
    return
  with open(src, encoding="utf-8") as f:
    markdown = f.read()
  markdown = transforms.remove_toc_markers(markdown)
  markdown = transforms.github_alerts(markdown)
  markdown = transforms.link_unpublished_files(markdown, path, published, url)
  markdown = labels.render_labels(markdown, url)
  if path == repo.NAV_SOURCE:
    markdown = NAV_SOURCE_FRONT_MATTER + markdown
  _write(dst, markdown)


def _write(path, content):
  """Write a text file, only if its content changes (the preview server rebuilds on every write)."""
  try:
    with open(path, encoding="utf-8") as f:
      if f.read() == content:
        return
  except OSError:
    pass
  os.makedirs(os.path.dirname(path), exist_ok=True)
  with open(path, "w", encoding="utf-8") as f:
    f.write(content)


def _remove_stale(published):
  """Remove the files of DOCS_DIR that are no longer published, and the directories left empty."""
  for root, dirs, files in os.walk(DOCS_DIR, topdown=False):
    for name in files:
      path = os.path.join(root, name)
      if os.path.relpath(path, DOCS_DIR).replace(os.sep, "/") not in published:
        _remove(path)
    if root != DOCS_DIR and not os.listdir(root):
      os.rmdir(root)


def _remove(path):
  """Remove a staged file that no longer exists in the repository."""
  try:
    os.remove(path)
  except OSError:
    pass
